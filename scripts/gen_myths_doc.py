"""Regenerate docs/myths.md from evals/myths.yaml (tracker task p9-10).

The yaml is the source of truth: each myth's exact tool call, the result of the live run and
its verdict and caveats. Run after editing it::

    uv run python scripts/gen_myths_doc.py          # rewrite docs/myths.md
    uv run python scripts/gen_myths_doc.py --check  # exit 1 if docs/myths.md is out of date

``tests/test_myths.py`` runs the check.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
MYTHS = ROOT / "evals" / "myths.yaml"
DOC = ROOT / "docs" / "myths.md"
VERDICTS = {
    "supported": "Supported (association)",
    "not_supported": "Not supported",
    "inconclusive": "Inconclusive",
}


def load() -> dict[str, Any]:
    return yaml.safe_load(MYTHS.read_text(encoding="utf-8"))


def _call(myth: dict[str, Any]) -> str:
    return f"{myth['tool']}({json.dumps(myth['args'], ensure_ascii=False)})"


def _ci(ci: list[float] | None) -> str:
    return "—" if not ci else f"{ci[0]:.3g} to {ci[1]:.3g}"


def _p(p: float | None) -> str:
    if p is None:
        return "—"
    return "< 1e-15" if p == 0 else f"{p:.2g}"


def render(data: dict[str, Any]) -> str:
    myths = data["myths"]
    counts = {v: sum(m["verdict"] == v for m in myths) for v in VERDICTS}
    lines = [
        "# Dota myth library",
        "",
        "<!-- generated by scripts/gen_myths_doc.py from evals/myths.yaml; do not edit by hand -->",
        "",
        f"{len(myths)} popular beliefs, each tested with one dota-insights tool call against "
        f"{data['server']} on {data['run_date']}. "
        f"{counts['supported']} supported, {counts['not_supported']} not supported, "
        f"{counts['inconclusive']} inconclusive.",
        "",
        "How to read a verdict:",
        "",
        "- **Supported** means the data shows the association the claim states, with a 95% "
        "interval that excludes no effect. It never means the condition causes the win: every "
        "result here is observational, and most of these metrics are partly a result of "
        "winning (a team that is ahead buys items sooner, takes more objectives and runes).",
        "- **Not supported** means the data does not show the claimed effect (or shows the "
        "opposite). That is not proof there is no effect, only that it is not visible at this "
        "sample size.",
        "- **Inconclusive** means the sample is too small, the interval is too wide, or the tool "
        "cannot separate the claim from the game state behind it.",
        "",
        "Most tests run on parsed league matches from OpenDota's explorer (pro and amateur "
        "leagues), the only bulk source of per-player stats and purchase logs; pub numbers may "
        "differ. Each myth is also an eval case in `evals/dataset.toml` (column *Eval*).",
        "",
        "| Myth | Verdict | n | Effect | 95% CI | p | Eval |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for m in myths:
        r = m["result"]
        lines.append(
            f"| [{m['claim']}](#{m['id']}) | {VERDICTS[m['verdict']]} | {r['sample_size']:,} | "
            f"{r['effect']} | {_ci(r['ci'])} | {_p(r['p_value'])} | `{m['eval_case']}` |"
        )
    for m in myths:
        r = m["result"]
        lines += [
            "",
            f'<a id="{m["id"]}"></a>',
            "",
            f"## {m['claim']}",
            "",
            f"**{VERDICTS[m['verdict']]}.** {r['effect']}; n = {r['sample_size']:,}, "
            f"95% CI {_ci(r['ci'])}, p = {_p(r['p_value'])}. Patch {r['patch']}, {r['source']}.",
            "",
            "```",
            _call(m),
            "```",
            "",
            *(f"- {c}" for c in m["caveats"]),
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    expected = render(load())
    if "--check" in argv:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != expected:
            print("docs/myths.md is out of date; run: uv run python scripts/gen_myths_doc.py")
            return 1
        return 0
    DOC.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
