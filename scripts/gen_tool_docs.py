"""Regenerate the tool and prompt reference in README.md from the registered MCP server.

The section between the ``tools:start`` and ``tools:end`` markers is rebuilt from each
domain module's tools (first docstring line, parameters) and the example questions in
``dota_insights.mcp.catalog``, which the landing page at ``/`` renders too.
Run after adding or changing a tool::

    uv run python scripts/gen_tool_docs.py          # rewrite README.md
    uv run python scripts/gen_tool_docs.py --check  # exit 1 if README.md is out of date

``tests/test_docs.py`` runs the check, so CI fails when the README drifts from the code.
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

from fastmcp import FastMCP

from dota_insights.mcp.catalog import EXAMPLES, domain_tools, first_sentence
from dota_insights.mcp.prompts import register_prompts

README = Path(__file__).resolve().parents[1] / "README.md"
START = "<!-- tools:start (generated by scripts/gen_tool_docs.py; do not edit by hand) -->"
END = "<!-- tools:end -->"

MAX_PARAMS = 4
TABLE_HEADER = "| Tool | Purpose | Key parameters | Example question |"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _params(schema: dict) -> str:
    props = list(schema.get("properties", {}))
    required = schema.get("required", [])
    names = [f"`{p}`" for p in required] + [f"`{p}`?" for p in props if p not in required]
    if not names:
        return "—"
    shown = names[:MAX_PARAMS]
    if len(names) > MAX_PARAMS:
        shown.append("…")
    return ", ".join(shown)


async def render() -> str:
    """The generated README section, markers included."""
    lines = [START, ""]
    total = 0
    body: list[str] = []
    for domain, tools in await domain_tools():
        total += len(tools)
        body += [f"### {domain.capitalize()}", ""]
        body += [TABLE_HEADER, "| --- | --- | --- | --- |"]
        for tool in tools:
            purpose = _cell(first_sentence(tool.description or ""))
            example = _cell(EXAMPLES.get(tool.name, "—"))
            body.append(f"| `{tool.name}` | {purpose} | {_params(tool.parameters)} | {example} |")
        body.append("")

    lines.append(
        f"{total} tools. `?` marks optional parameters; most aggregate tools also take a "
        "`filters` object (patch, rank bracket, position, game mode, min_sample)."
    )
    lines += ["", *body]

    prompts_server = FastMCP("prompts")
    register_prompts(prompts_server)
    lines += ["### Prompts", "", "| Prompt | What it does | Arguments |", "| --- | --- | --- |"]
    for prompt in sorted(await prompts_server.list_prompts(), key=lambda p: p.name):
        args = ", ".join(
            f"`{a.name}`" if a.required else f"`{a.name}`?" for a in prompt.arguments or []
        )
        lines.append(f"| `{prompt.name}` | {_cell(prompt.description or '')} | {args or '—'} |")
    lines += ["", END]
    return "\n".join(lines)


def updated_readme(readme: str, section: str) -> str:
    """``readme`` with the generated section replaced by ``section``."""
    try:
        head, rest = readme.split(START, 1)
        _, tail = rest.split(END, 1)
    except ValueError:
        raise SystemExit(f"README.md must contain the markers {START!r} and {END!r}") from None
    return head + section + tail


def main(argv: list[str]) -> int:
    current = README.read_text(encoding="utf-8")
    expected = updated_readme(current, asyncio.run(render()))
    if "--check" in argv:
        if current != expected:
            print("README.md is out of date; run: uv run python scripts/gen_tool_docs.py")
            return 1
        return 0
    README.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
