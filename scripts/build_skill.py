"""Build the Dota Insights agent skill (``skill/dota-insights``) for skill marketplaces.

``references/tools.md`` is generated from the registered tools, like the README table, so the
skill cannot drift from the server. The zip has the single top-level folder that SKILL.md
marketplaces expect (``dota-insights/SKILL.md``), with no OS files::

    uv run python scripts/build_skill.py          # rewrite tools.md and build the zip in dist/
    uv run python scripts/build_skill.py --check  # exit 1 if tools.md is out of date

``tests/test_skill.py`` runs the check and validates the zip layout.
"""

from __future__ import annotations

import asyncio
import sys
import zipfile
from pathlib import Path

from dota_insights.mcp.catalog import catalog

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skill" / "dota-insights"
TOOLS = SKILL / "references" / "tools.md"
ZIP = ROOT / "dist" / "dota-insights-skill.zip"
SKIPPED = {".DS_Store", "Thumbs.db"}


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


async def render_tools() -> str:
    lines = [
        "# Dota Insights tools",
        "",
        "<!-- generated by scripts/build_skill.py from the server's tools; do not edit by hand -->",
        "",
        "Required arguments are listed; every tool also takes optional ones (most take `filters`).",
        "The server's own tool descriptions have the full parameter docs.",
    ]
    for domain in await catalog():
        lines += ["", f"## {domain.name}", "", "| Tool | Purpose | Required | Example question |"]
        lines.append("| --- | --- | --- | --- |")
        for tool in domain.tools:
            required = ", ".join(f"`{p}`" for p in tool.required) or "—"
            example = _cell(tool.example or "—")
            lines.append(f"| `{tool.name}` | {_cell(tool.purpose)} | {required} | {example} |")
    return "\n".join(lines) + "\n"


def skill_files() -> list[Path]:
    return sorted(
        p for p in SKILL.rglob("*") if p.is_file() and p.name not in SKIPPED and not p.is_symlink()
    )


def build_zip(target: Path = ZIP) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in skill_files():
            archive.write(path, (SKILL.name / path.relative_to(SKILL)).as_posix())
    return target


def main(argv: list[str]) -> int:
    expected = asyncio.run(render_tools())
    if "--check" in argv:
        if TOOLS.read_text(encoding="utf-8") != expected:
            print("skill/dota-insights/references/tools.md is stale; run scripts/build_skill.py")
            return 1
        return 0
    TOOLS.write_text(expected, encoding="utf-8")
    print(f"wrote {build_zip().relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
