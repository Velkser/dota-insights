def test_patch_change_is_spelled_out():
    before = week({ALL_RANKS: 10}, {})
    before.patches.clear()
    before.patches["7.41"] = 10
    after = week({ALL_RANKS: 10}, {})
    after.patches.clear()
    after.patches.update({"7.41b": 8, "7.41": 2})
    text = texts.patch_text(weekly_report(before, after))
    assert text == "патч 7.41b (в сравнении участвуют патчи 7.41, 7.41b)"


# Files and CLI


def run_cli(factory, tmp_path, *extra: str) -> int:
    args = cli._parser().parse_args(
        ["weekly", "--out", str(tmp_path / "out"), "--end", END.isoformat(), "--min-games", "100"]
        + list(extra)
    )
    return cli.weekly(args, factory)


def test_cli_writes_dated_folder(seeded, tmp_path, capsys):
    assert run_cli(seeded, tmp_path) == 0
    folder = tmp_path / "out" / "2026-11-01"
    names = {p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()}
    assert {
        "README.md",
        "weekly-meta.md",
        "weekly-meta-by-rank.md",
        "weekly-winrate.png",
        "weekly-pickrate.png",
        "report.json",
    } <= names
    drafts = sorted(n for n in names if n.startswith("insights/"))
    assert drafts and drafts[0].startswith("insights/01-")
    for png in ("weekly-winrate.png", "weekly-pickrate.png"):
        assert (folder / png).read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    readme = (folder / "README.md").read_text(encoding="utf-8")
    assert all(f"`{n}`" in readme for n in names)
    data = json.loads((folder / "report.json").read_text(encoding="utf-8"))
    assert data["after"]["matches"]["0"] == 1200 and data["patch"] == "7.41"
    assert "1200 matches this week" in capsys.readouterr().out


def test_cli_survives_chart_failure(seeded, tmp_path, monkeypatch):
    def broken(spec, scale=2.0):
        raise RuntimeError("no renderer")

    monkeypatch.setattr(report, "render_png", broken)
    assert run_cli(seeded, tmp_path) == 0
    folder = tmp_path / "out" / "2026-11-01"
    assert not (folder / "weekly-winrate.png").exists()
    assert "no renderer" in (folder / "README.md").read_text(encoding="utf-8")
    assert (folder / "weekly-meta.md").exists()


def test_chart_spec_uses_shared_chart_code(seeded):
    with seeded() as session:
        after = matches_week(session, AFTER_START, END)
        before = matches_week(session, BEFORE_START, AFTER_START)
    result = weekly_report(before, after, min_games=100, top=3)
    spec = report.chart_spec(result.movers[0], result, "winrate")
    assert spec["config"] == charts.CONFIG
    values = [r["y"] for r in spec["data"]["values"]]
    assert values == sorted(values, reverse=True) and values[0] > 0 > values[-1]


def test_cli_on_empty_database(factory, tmp_path, capsys):
    assert run_cli(factory, tmp_path, "--no-charts") == 0
    folder = tmp_path / "out" / "2026-11-01"
    assert "Недостаточно данных" in (folder / "weekly-meta.md").read_text(encoding="utf-8")
    assert not list((folder / "insights").iterdir())
    assert "warning: no hero" in capsys.readouterr().out
