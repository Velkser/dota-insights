PATCHES = [
    {"id": 59, "name": "7.40", "date": "2025-12-16T00:50:40.281Z"},
    {"id": 60, "name": "7.41", "date": "2026-03-24T00:50:59.580Z"},
]
END = date(2026, 11, 2)  # a Monday: the reported week is 26 Oct - 1 Nov
AFTER_START = END - timedelta(days=7)
BEFORE_START = END - timedelta(days=14)
POOL = list(range(1, 21))
STRONGER = 1  # Anti-Mage wins much more in the reported week
POPULAR = 2  # Axe is picked much more in the reported week


def generate(week_start: date, matches: int, rank_tier: int, *, after: bool, seed: int):
    """Public-match rows for one week; in the ``after`` week STRONGER wins and POPULAR is picked."""
    rng = random.Random(seed)
    rows = []
    start = datetime.combine(week_start, datetime.min.time(), tzinfo=UTC)
    for i in range(matches):
        heroes = rng.sample(POOL, 10)
        if after and POPULAR not in heroes and rng.random() < 0.6:
            heroes[rng.randrange(10)] = POPULAR
        radiant, dire = heroes[:5], heroes[5:]
        edge = 0.2 if after else 0.0
        p_radiant = 0.5 + edge * ((STRONGER in radiant) - (STRONGER in dire))
        rows.append(
            {
                "match_id": seed * 100_000 + i,
                "start_time": int((start + timedelta(minutes=10 * i % (7 * 24 * 60))).timestamp()),
                "duration": 2400,
                "lobby_type": 7,
                "game_mode": 22,
                "avg_rank_tier": rank_tier,
                "radiant_win": rng.random() < p_radiant,
                "radiant_team": radiant,
                "dire_team": dire,
            }
        )
    return rows


@pytest.fixture
def factory(tmp_path) -> sessionmaker[Session]:
    engine = create_engine(f"sqlite:///{tmp_path / 'insights.db'}")
    Base.metadata.create_all(engine)
    factory = sessionmaker(engine, expire_on_commit=False)
    with factory.begin() as session:
        sync_patches(session, PATCHES)
    yield factory
    engine.dispose()


@pytest.fixture
def seeded(factory) -> sessionmaker[Session]:
    rows = (
        generate(BEFORE_START, 900, 54, after=False, seed=1)
        + generate(AFTER_START, 900, 54, after=True, seed=2)
        + generate(BEFORE_START, 300, 14, after=False, seed=3)
        + generate(AFTER_START, 300, 14, after=True, seed=4)
    )
    with factory.begin() as session:
        store_summaries(session, rows)
    return factory


def week(matches: dict[int, int], heroes: dict[tuple[int, int], tuple[int, int]]) -> WeekCounts:
    counts = WeekCounts(AFTER_START, END, "matches")
    counts.matches.update(matches)
    counts.heroes.update(heroes)
    counts.patches["7.41"] = matches.get(ALL_RANKS, 0)
    return counts


# Loaders


def test_matches_week_counts_by_bracket_and_window(factory):
    inside = datetime.combine(AFTER_START, datetime.min.time(), tzinfo=UTC)
    rows = [
        generate(AFTER_START, 1, 54, after=False, seed=5)[0],
        generate(AFTER_START, 1, 80, after=False, seed=6)[0],  # Immortal -> Divine
        generate(AFTER_START, 1, 75, after=False, seed=7)[0],
        generate(AFTER_START, 1, 0, after=False, seed=8)[0],  # unknown rank: left out
        # Exactly at the end of the week: belongs to the next one.
        generate(END, 1, 54, after=False, seed=9)[0],
    ]
    rows[0]["start_time"] = int(inside.timestamp())
    with factory.begin() as session:
        store_summaries(session, rows)
    with factory() as session:
        counts = matches_week(session, AFTER_START, END)
    assert dict(counts.matches) == {ALL_RANKS: 3, 5: 1, 7: 2}
    assert dict(counts.patches) == {"7.41": 3}
    assert sum(g for (b, _), (g, _) in counts.heroes.items() if b == ALL_RANKS) == 30
    assert sum(w for (b, _), (_, w) in counts.heroes.items() if b == 7) == 10


def test_opendota_week_uses_the_last_snapshot_of_the_week(factory):
    raw = [
        {"id": 1, "5_pick": 400, "5_win": 220, "8_pick": 100, "8_win": 40},
        {"id": 2, "5_pick": 600, "5_win": 290, "7_pick": 50, "7_win": 25},
    ]
    with factory.begin() as session:
        for day in (AFTER_START, END - timedelta(days=1), END):
            session.add_all(HeroStatsDaily(**r) for r in hero_stats_rows(raw, day))
    with factory() as session:
        counts = load_week(session, "opendota", AFTER_START, END)
    assert counts.snapshot_day == END - timedelta(days=1)
    assert counts.heroes[(5, 1)] == (400, 220)
    assert counts.heroes[(7, 1)] == (100, 40)
    assert counts.heroes[(ALL_RANKS, 2)] == (650, 315)
    assert counts.matches[5] == 100  # 1000 picks / 10
    assert dict(counts.patches) == {"7.41": counts.total_matches}


def test_opendota_week_without_snapshot_is_empty(factory):
    with factory() as session:
        counts = load_week(session, "opendota", AFTER_START, END)
    assert counts.total_matches == 0 and counts.heroes == {} and counts.snapshot_day is None


# Changes and anomalies


def test_compare_needs_min_games_in_both_weeks():
    before = week({ALL_RANKS: 1000}, {(0, 1): (300, 150), (0, 2): (99, 50), (0, 3): (500, 250)})
    after = week({ALL_RANKS: 1000}, {(0, 1): (320, 180), (0, 2): (400, 200), (0, 4): (500, 1)})
    changes = compare(before, after, min_games=100)
    assert [c.hero_id for c in changes] == [1]
    assert changes[0].delta("winrate") == pytest.approx(180 / 320 - 0.5)
    assert changes[0].delta("pickrate") == pytest.approx(0.02)


def test_detect_anomalies_needs_significance_and_size():
    def change(hero_id, wins_after, games_after=2000, bracket=ALL_RANKS):
        return HeroChange(bracket, hero_id, 2000, 1000, 10_000, games_after, wins_after, 10_000)

    found = detect_anomalies(
        [
            change(1, 1200),  # +10 points, z ~ 6.3
            change(2, 1010),  # +0.5 points: noise
            change(3, 1000, games_after=3000),  # pick rate 20% -> 30%
            change(1, 1150, bracket=5),  # same hero and metric, weaker: dropped
        ]
    )
    assert [(a.change.hero_id, a.change.bracket, a.metric) for a in found] == [
        (3, ALL_RANKS, "pickrate"),
        (3, ALL_RANKS, "winrate"),
        (1, ALL_RANKS, "winrate"),
    ]
    assert all(a.q_value <= 0.05 for a in found)
    # A large but tiny change is not an anomaly however small its p-value.
    big = HeroChange(0, 9, 200_000, 100_000, 10**6, 200_000, 101_000, 10**6)
    assert detect_anomalies([big]) == []
    assert detect_anomalies([big], min_wr_delta=0.001)[0].metric == "winrate"


def test_weekly_report_on_fixture_matches(seeded):
    with seeded() as session:
        after = matches_week(session, AFTER_START, END)
        before = matches_week(session, BEFORE_START, AFTER_START)
    assert (before.total_matches, after.total_matches) == (1200, 1200)
    result = weekly_report(before, after, min_games=100, top=3)
    assert [m.bracket for m in result.movers] == [ALL_RANKS, 1, 5]
    overall = result.movers[0]
    assert overall.winrate_up[0].hero_id == STRONGER
    assert overall.pickrate_up[0].hero_id == POPULAR
    assert all(c.delta("winrate") < 0 for c in overall.winrate_down)
    assert len(overall.winrate_up) == 3
    flagged = {(a.change.hero_id, a.metric) for a in result.anomalies}
    assert {(STRONGER, "winrate"), (POPULAR, "pickrate")} <= flagged
    assert result.patch == "7.41" and not result.patch_changed


